'use strict';

/**
 * Forecast backtest harness.
 *
 * Generates a deterministic synthetic ledger (no customer data, no network),
 * trains the payer-history model on 70% of settled invoices, and scores it
 * against two baselines. Writes docs/FORECAST_BACKTEST.md so the number in the
 * README is reproducible with `npm run backtest`.
 */

const fs = require('node:fs');
const path = require('node:path');
const { backtest, toDay } = require('../src/forecast');

function mulberry32(seed) {
  let state = seed >>> 0;
  return function random() {
    state += 0x6D2B79F5;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

function addDays(iso, days) {
  const date = new Date(`${iso}T00:00:00.000Z`);
  date.setUTCDate(date.getUTCDate() + days);
  return date.toISOString().slice(0, 10);
}

function buildSyntheticLedger() {
  const random = mulberry32(20261112);
  const payers = [
    { name: 'Northwind Studio', lateness: 1, spread: 2, weight: 1.1 },
    { name: 'Acme Design Co', lateness: 9, spread: 4, weight: 1.4 },
    { name: 'Harbor & Pine', lateness: -2, spread: 1, weight: 0.8 },
    { name: 'Meridian Labs', lateness: 16, spread: 6, weight: 1.6 },
    { name: 'Globex', lateness: 4, spread: 3, weight: 1 },
    { name: 'Initech', lateness: 22, spread: 8, weight: 1.2 },
    { name: 'Umbrella Freelance', lateness: 0, spread: 2, weight: 0.7 },
    { name: 'Soylent Studio', lateness: 6, spread: 5, weight: 1.3 }
  ];
  const invoices = [];
  for (const payer of payers) {
    const email = `${payer.name.toLowerCase().replace(/[^a-z]+/g, '.')}@example.com`;
    for (let month = 0; month < 18; month += 1) {
      const dueDate = addDays('2025-01-06', month * 28 + Math.floor(random() * 4));
      const jitter = Math.round((random() * 2 - 1) * payer.spread);
      const lateness = Math.max(-10, payer.lateness + jitter);
      const paidDate = addDays(dueDate, lateness);
      invoices.push({
        id: `${payer.name.slice(0, 3)}-${month}`,
        customer: { name: payer.name, email },
        status: 'PAID',
        dueDate,
        paidAt: `${paidDate}T12:00:00.000Z`,
        updatedAt: `${paidDate}T12:00:00.000Z`,
        total: Math.round((400 + random() * 3600) * 100) / 100,
        currency: 'USD'
      });
    }
  }
  return invoices;
}

function pct(value) {
  return `${(value * 100).toFixed(1)}%`;
}

function days(value) {
  return `${Number(value).toFixed(2)} d`;
}

function main() {
  const ledger = buildSyntheticLedger();
  const result = backtest(ledger, { trainRatio: 0.7 });
  const due = result.metrics.dueDate;
  const global = result.metrics.globalMedian;
  const payer = result.metrics.payerMedian;
  const improvement = ((due.mae - payer.mae) / due.mae) * 100;

  const lines = [
    '# Forecast backtest',
    '',
    `Generated by \`npm run backtest\` on ${new Date().toISOString().slice(0, 10)}. This file is committed so the number quoted in the README can be reproduced and checked.`,
    '',
    '## What is being tested',
    '',
    'The forecast predicts **when an open invoice will actually be paid**, not just its due date:',
    '',
    '```text',
    'expected payment date = due date + median observed lateness for that payer',
    '```',
    '',
    'If a payer has fewer than two settled invoices, the model falls back to the portfolio median, then to the due date. The same pure functions run in the app (`src/forecast.js`); the UI shows the basis and confidence for every invoice.',
    '',
    '## Data',
    '',
    'The harness generates a deterministic **synthetic** ledger (seed `20261112`): 8 payers with different lateness behaviour, 18 monthly invoices each, and seeded jitter. It contains no real customer data and makes no network calls. Swap `buildSyntheticLedger()` for exported CSV rows to run the same evaluation on real history.',
    '',
    `- Settled invoices: **${ledger.length}**`,
    `- Training rows: **${result.trainCount}** · test rows: **${result.testCount}**`,
    `- Payers: **${result.payerCount}**`,
    '',
    '## Results (test split, 70/30 chronological)',
    '',
    '| Model | MAE | RMSE | Within 3 days | Within 7 days | Exact date |',
    '| --- | ---: | ---: | ---: | ---: | ---: |',
    `| Due-date baseline | ${days(due.mae)} | ${days(due.rmse)} | ${pct(due.within3)} | ${pct(due.within7)} | ${pct(due.exact)} |`,
    `| Global median lateness | ${days(global.mae)} | ${days(global.rmse)} | ${pct(global.within3)} | ${pct(global.within7)} | ${pct(global.exact)} |`,
    `| **Payer median lateness (this app)** | **${days(payer.mae)}** | **${days(payer.rmse)}** | **${pct(payer.within3)}** | **${pct(payer.within7)}** | **${pct(payer.exact)}** |`,
    '',
    `Payer-aware forecasting reduces mean absolute error by **${improvement.toFixed(1)}%** versus assuming every invoice is paid on its due date.`,
    '',
    '## Reproduce',
    '',
    '```sh',
    'npm run backtest',
    '```',
    '',
    'The command is deterministic: the same seed produces the same table. `tests/forecast.test.js` asserts the payer-aware model beats the due-date baseline so the claim cannot silently regress.',
    '',
    '## Honest boundaries',
    '',
    '- This is a synthetic calibration harness, not a claim about real merchants. It proves the estimator and the evaluation are wired together; the published number should be replaced with a real backtest before making production claims.',
    '- Cash forecasting is decision support, not a guarantee. The UI labels the expected date with its basis and confidence.',
    '- The model only uses each invoice due date and payer lateness; it does not yet use invoice amount, reminders, or seasonality.'
  ];

  const output = path.join(process.cwd(), 'docs', 'FORECAST_BACKTEST.md');
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, `${lines.join('\n')}\n`, 'utf8');

  console.log('Forecast backtest (synthetic ledger)');
  console.log(`  settled invoices: ${ledger.length} · train ${result.trainCount} · test ${result.testCount} · payers ${result.payerCount}`);
  console.log(`  due-date baseline MAE: ${days(due.mae)}`);
  console.log(`  global median MAE:     ${days(global.mae)}`);
  console.log(`  payer median MAE:      ${days(payer.mae)}  (${improvement.toFixed(1)}% better than due date)`);
  console.log(`  wrote ${path.relative(process.cwd(), output)}`);
}

if (require.main === module) main();

module.exports = { buildSyntheticLedger, mulberry32 };
